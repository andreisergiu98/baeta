import { readdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import test from '@baeta/testing';

const fixturePath = resolve(import.meta.dirname, '.');

function findGeneratedFiles(dir: string): string[] {
	const results: string[] = [];
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const fullPath = resolve(dir, entry.name);
		if (entry.isDirectory()) {
			results.push(...findGeneratedFiles(fullPath));
		} else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts')) {
			results.push(fullPath);
		}
	}
	return results;
}

test('all generated files use .js import extensions for relative imports', (t) => {
	const generatedFiles = [
		...findGeneratedFiles(resolve(fixturePath, 'src/modules')),
		...findGeneratedFiles(resolve(fixturePath, 'src/__generated__')),
	];

	t.true(generatedFiles.length > 0);

	for (const filePath of generatedFiles) {
		const content = readFileSync(filePath, 'utf-8');
		if (!content.includes('This file was generated by Baeta')) continue;
		const relativeImports = content.matchAll(/from\s+["'](\.[^"']+)["']/g);

		for (const match of relativeImports) {
			const importPath = match[1];
			t.true(
				importPath.endsWith('.js'),
				`${filePath}: relative import "${importPath}" should use .js extension`,
			);
		}
	}
});
